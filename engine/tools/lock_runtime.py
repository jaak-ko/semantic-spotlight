"""Writes runtime-requirements.txt: the runtime's full dependency closure at the versions in the tested
.venv, each pinned with the sha256 of its arm64-macOS cp312 wheels (or pure/abi3 wheels), from PyPI's
JSON API. No wheel is downloaded. hf-xet is left out on purpose (see README).

Usage: .venv/bin/python engine/tools/lock_runtime.py
"""
import json
import ssl
import urllib.request
from importlib import metadata
from pathlib import Path

import certifi
from packaging.markers import default_environment
from packaging.requirements import Requirement
from packaging.utils import canonicalize_name, parse_wheel_filename

ROOT = Path(__file__).resolve().parents[2]
ROOTS = ["torch", "sentence-transformers", "numpy", "snowballstemmer"]
EXCLUDE = {"hf-xet"}  # huggingface_hub runs without it; xet downloads are disabled in code
ENV = {**default_environment(), "platform_system": "Darwin", "sys_platform": "darwin",
       "platform_machine": "arm64", "python_version": "3.12", "python_full_version": "3.12.16",
       "implementation_name": "cpython", "platform_python_implementation": "CPython", "extra": ""}


def _ok_wheel(fname):
    """A wheel this runtime can install: pure Python, or cp312 / abi3 built for arm64 macOS."""
    tags = parse_wheel_filename(fname)[3]
    for t in tags:
        mac_arm = "macosx" in t.platform and ("arm64" in t.platform or "universal2" in t.platform)
        py_ok = t.interpreter in ("py3", "py312", "cp312") or (
            t.abi == "abi3" and t.interpreter.startswith("cp3") and int(t.interpreter[3:]) <= 12)
        if t.platform == "any" and py_ok:
            return True
        if mac_arm and py_ok:
            return True
    return False


def closure():
    seen, todo = {}, list(ROOTS)
    while todo:
        name = canonicalize_name(todo.pop())
        if name in seen or name in EXCLUDE:
            continue
        dist = metadata.distribution(name)
        seen[name] = dist.version
        for req in dist.requires or []:
            r = Requirement(req)
            if r.marker and not r.marker.evaluate(ENV):
                continue
            todo.append(r.name)
    return seen


def hashes(name, version):
    url = f"https://pypi.org/pypi/{name}/{version}/json"
    ctx = ssl.create_default_context(cafile=certifi.where())  # python.org builds need certifi's CA bundle
    with urllib.request.urlopen(url, timeout=60, context=ctx) as f:
        files = json.load(f)["urls"]
    out = [(x["filename"], x["digests"]["sha256"]) for x in files
           if x["packagetype"] == "bdist_wheel" and _ok_wheel(x["filename"])]
    if not out:
        raise SystemExit(f"no arm64 macOS cp312 wheel for {name}=={version}")
    return out


def main():
    pins = closure()
    lines = ["# Generated by engine/tools/lock_runtime.py. Do not edit: every version and hash is pinned.",
             "# Installed by package_runtime.sh with --require-hashes --no-deps --only-binary=:all:."]
    for name in sorted(pins):
        version = pins[name]
        entries = hashes(name, version)
        first = f"{name}=={version} \\"
        lines.append(first)
        for i, (fname, digest) in enumerate(sorted(entries)):
            tail = " \\" if i < len(entries) - 1 else ""
            lines.append(f"    --hash=sha256:{digest}{tail}")
    (ROOT / "engine" / "runtime-requirements.txt").write_text("\n".join(lines) + "\n")
    print(f"wrote runtime-requirements.txt: {len(pins)} packages")


if __name__ == "__main__":
    main()
