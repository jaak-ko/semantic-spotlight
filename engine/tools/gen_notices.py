"""Regenerates THIRD_PARTY_NOTICES.md (repo root) from the packages inside engine/dist/runtime.

Usage: python engine/tools/gen_notices.py [runtime_dir]

For each installed package it reads the licence files shipped in its .dist-info (including the
licenses/ subfolder) and the License / License-Expression / classifier metadata. A package with neither
is listed as UNDETERMINED: nothing is guessed. CPython, python-build-standalone and the e5 model are
added from their own sources (noted below).
"""
import re
import sys
from email.parser import Parser
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DEFAULT_RUNTIME = ROOT / "engine" / "dist" / "runtime"
LICENCE_FILE = re.compile(r"^(LICEN[CS]E|COPYING|NOTICE)", re.IGNORECASE)

EXTRA = [
    ("CPython 3.12.16", "PSF-2.0 (Python Software Foundation License)",
     "Shipped as python/lib/python3.12/LICENSE.txt inside the runtime.",
     "python/lib/python3.12/LICENSE.txt"),
    ("python-build-standalone 20261026", "MPL-2.0 (the project's build tooling; the bundled Python keeps the PSF licence)",
     "Packaging of CPython used to build the runtime. Source: https://github.com/astral-sh/python-build-standalone",
     None),
    ("intfloat/multilingual-e5-small (model weights, downloaded at first launch)", "MIT",
     "Model card metadata: license: mit. Source: https://huggingface.co/intfloat/multilingual-e5-small",
     None),
]


def _meta(dist: Path):
    return Parser().parsestr((dist / "METADATA").read_text(encoding="utf-8", errors="replace"))


def _licence_of(meta):
    expr = (meta.get("License-Expression") or "").strip()
    if expr:
        return expr
    first = (meta.get("License") or "").strip().splitlines()
    lic = first[0].strip() if first else ""
    if lic and lic.upper() not in ("UNKNOWN", "NONE") and len(lic) <= 60 and "copyright" not in lic.lower():
        return lic
    classifiers = [c.split("::")[-1].strip() for c in meta.get_all("Classifier") or []
                   if c.startswith("License ::")]
    if classifiers:
        return ", ".join(classifiers)
    return "see licence text below" if lic else None


def _licence_files(dist: Path):
    files = [f for f in dist.rglob("*") if f.is_file() and LICENCE_FILE.match(f.name)]
    return sorted(files)


def collect(runtime: Path):
    rows = []
    for dist in sorted(runtime.glob("python/lib/python3.12/site-packages/*.dist-info")):
        meta = _meta(dist)
        name, version = meta.get("Name", dist.name), meta.get("Version", "?")
        licence = _licence_of(meta)
        files = _licence_files(dist)
        texts = [(f.relative_to(dist).as_posix(), f.read_text(encoding="utf-8", errors="replace")) for f in files]
        copyright_line = next((ln.strip() for _, t in texts for ln in t.splitlines()
                               if ln.strip().lower().startswith("copyright")), None)
        rows.append({"name": name, "version": version, "licence": licence or "UNDETERMINED",
                     "copyright": copyright_line, "texts": texts})
    return sorted(rows, key=lambda r: r["name"].lower())


def render(rows, runtime: Path) -> str:
    out = ["# Third-party notices", "",
           "The Semantic Spotlight application is MIT licensed (see `LICENSE`). It ships with the third-party",
           "software below, each under its own licence. Generated by `engine/tools/gen_notices.py` from the",
           "packages in the runtime; regenerate after changing the dependency set.", "",
           "## Summary", "", "| Package | Version | Licence |", "|---|---|---|"]
    for name, lic, _, _ in EXTRA:
        out.append(f"| {name} | - | {lic} |")
    for r in rows:
        out.append(f"| {r['name']} | {r['version']} | {r['licence']} |")
    undetermined = [r["name"] for r in rows if r["licence"] == "UNDETERMINED"]
    out += ["", f"Packages whose licence could not be determined from their shipped files or metadata: "
                f"{', '.join(undetermined) or 'none'}.", ""]
    out += ["## Added from their own sources", ""]
    for name, lic, note, path in EXTRA:
        out += [f"### {name}", f"Licence: {lic}", "", note, ""]
        if path and (runtime / path).is_file():
            out += ["~~~~", (runtime / path).read_text(encoding="utf-8", errors="replace").rstrip(), "~~~~", ""]
    out += ["## Packages", ""]
    for r in rows:
        out += [f"### {r['name']} {r['version']}", f"Licence: {r['licence']}"]
        if r["copyright"]:
            out.append(f"Copyright: {r['copyright']}")
        out.append("")
        for fname, text in r["texts"]:
            out += [f"File `{fname}`:", "", "~~~~", text.rstrip(), "~~~~", ""]
        if not r["texts"]:
            out += ["No licence file is shipped with this package; the licence above is from its metadata.", ""]
    return "\n".join(out) + "\n"


def main(argv):
    runtime = Path(argv[1]) if len(argv) > 1 else DEFAULT_RUNTIME
    rows = collect(runtime)
    (ROOT / "THIRD_PARTY_NOTICES.md").write_text(render(rows, runtime), encoding="utf-8")
    print(f"wrote THIRD_PARTY_NOTICES.md: {len(rows)} packages, "
          f"{sum(r['licence'] == 'UNDETERMINED' for r in rows)} undetermined")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
